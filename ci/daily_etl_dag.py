"""Render the drop-major daily orchestration; registry definitions win."""
import json
from pathlib import Path

import yaml

from drops import DROPS, drop_params
from registry import load, tables, topo_order

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "resources/wwi_daily_etl.job.yml"


def stage(unit, spec):
    if unit == "governance":
        return "governance"
    owned = tables(spec)
    if any(t.startswith(("bronze.", "silver.")) for t in owned):
        return "silver"
    if unit == "p5_gold_seed" or any(t.startswith("gold.integration_") for t in owned):
        return "seed"
    for kind in ("dim", "fact", "report"):
        if any(t.startswith(f"gold.{kind}_") for t in owned):
            return kind
    raise ValueError(f"Unclassified unit: {unit}")


def definitions():
    planned = json.loads((ROOT / "src/orchestration/planned_units.json").read_text())
    registry = load(ROOT / "src/sql/units/registry.json", ROOT / "src/parity/contract.json")
    return registry, {**planned, **registry}


def generate():
    registry, units = definitions()
    ordered = [u for u in topo_order(units, "*") if u != "governance"]
    manifest = json.loads((ROOT / "golden/manifest.json").read_text())
    tasks = []
    placeholders = {f"{d}_{u}" for d in DROPS for u in ordered if u not in registry}

    def edges(keys):
        return [dict(task_key=k, **({"outcome": "true"} if k in placeholders else {}))
                for k in dict.fromkeys(keys)]

    def compute(key, script, args, dependencies):
        return dict(task_key=key, depends_on=edges(dependencies), environment_key="orchestration",
                    spark_python_task=dict(python_file=f"../src/{script}", parameters=args))

    for index, drop in enumerate(DROPS):
        for unit in ordered:
            spec = units[unit]
            deps = [f"{drop}_{d}" for d in spec["depends_on"]]
            if not deps and index:
                deps.append(f"{DROPS[index - 1]}_parity")
            if stage(unit, spec) != "silver":
                deps.append(f"{drop}_verify_silver")
            task = dict(task_key=f"{drop}_{unit}")
            if deps:
                task["depends_on"] = edges(deps)
            if unit in registry:
                task["run_job_task"] = dict(job_id="${resources.jobs." + spec["job"] + ".id}",
                                            job_parameters=drop_params(manifest, drop))
            else:
                task["condition_task"] = dict(op="EQUAL_TO", left="1", right="1")
            tasks.append(task)
        tasks.append(compute(f"{drop}_verify_silver", "orchestration/verify_silver.py",
                             ["--catalog", "${var.catalog}", "--schema", "${var.silver_schema}", "--drop", drop],
                             [f"{drop}_{u}" for u in ordered if stage(u, units[u]) == "silver"]))
        tasks.append(compute(f"{drop}_parity", "parity/parity_check.py",
                             ["--suffix", "${var.schema_suffix}", "--catalog", "${var.catalog}",
                              "--drop", drop, "--warehouse-id", "${var.warehouse_id}",
                              "--output", f"/tmp/wwi_daily_etl_{drop}_parity.json"],
                             [f"{drop}_{u}" for u in ordered if stage(u, units[u]) != "silver"]
                             + [f"{drop}_verify_silver"]))
    final = dict(task_key="governance", depends_on=edges([f"{d}_parity" for d in DROPS]), run_if="NONE_FAILED")
    if "governance" in registry:
        final["run_job_task"] = dict(job_id="${resources.jobs." + registry["governance"]["job"] + ".id}")
    else:
        final["condition_task"] = dict(op="EQUAL_TO", left="1", right="1")
    tasks.append(final)
    job = dict(name="${var.job_name_prefix}wwi_daily_etl", max_concurrent_runs=1,
               queue=dict(enabled=True), timeout_seconds=7200,
               schedule=dict(quartz_cron_expression="0 30 1 * * ?", timezone_id="UTC", pause_status="PAUSED"),
               health=dict(rules=[dict(metric="RUN_DURATION_SECONDS", op="GREATER_THAN", value=3600)]),
               environments=[dict(environment_key="orchestration", spec=dict(environment_version="2",
                                   dependencies=["databricks-sdk>=0.85,<1"]))], tasks=tasks)
    bad = compute("dev_bad_row_quarantine", "orchestration/dev_bad_rows.py",
                  ["--catalog", "${var.catalog}", "--schema", "${var.silver_schema}"], ["D2_verify_silver"])
    dev = dict(tasks=[bad, dict(task_key="governance", depends_on=[dict(task_key="dev_bad_row_quarantine")])])
    return dict(resources=dict(jobs=dict(wwi_daily_etl=job)),
                targets=dict(dev=dict(resources=dict(jobs=dict(wwi_daily_etl=dev)))))


def render():
    return "# Generated by ci/daily_etl_dag.py; do not edit.\n" + yaml.safe_dump(generate(), sort_keys=False)


if __name__ == "__main__":
    OUTPUT.write_text(render())
